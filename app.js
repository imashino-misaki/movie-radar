function icsEsc(s) { return String(s).replace(/\\/g, "\\\\").replace(/;/g, "\\;").replace(/,/g, "\\,").replace(/\n/g, "\\n"); }
// RFC 5545 3.1: a content line longer than 75 octets continues after CRLF and one space (the space
// counts toward the next line); octets are UTF-8 and a code point is never split
const U8 = new TextEncoder();
function icsFold(line) {
  let out = "", n = 0;
  for (const ch of line) {
    const len = U8.encode(ch).length;
    if (n + len > 75) { out += "\r\n "; n = 1; }
    out += ch; n += len;
  }
  return out;
}
