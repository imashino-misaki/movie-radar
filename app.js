// MRS: per-source status from the last run (data/site/status.js). A source is stale after
// MRS.stale hours without a good run (two collection intervals; see collector/site.py).
function freshness() {
  if (!MRS || !MRS.src) return { rows: [], banner: "" };
  const now = Date.now(), lim = MRS.stale * 36e5;
  const ago = iso => { const h = (now - Date.parse(iso)) / 36e5; return h < 1 ? "1시간 안" : h < 48 ? `${Math.round(h)}시간` : `${Math.round(h / 24)}일`; };
  const rows = MRS.src.map(([key, label, st, ok]) => {
    const old = !ok || now - Date.parse(ok) > lim, err = st !== "ok";
    const text = !ok ? "아직 가져오지 못함" : err ? `오류 · 마지막 성공 ${ago(ok)} 전` : `${ago(ok)} 전 확인`;
    return { key, label, ok, err, old, bad: err || old, text };
  });
  let banner = "";
  if (MRS.run && now - Date.parse(MRS.run) > lim) banner = `정보가 ${ago(MRS.run)}째 갱신되지 않았어요. 평소에는 ${MRS.iv}시간마다 갱신돼요.`;
  else {
    const bad = rows.filter(r => r.bad);
    const one = r => !r.ok ? `${r.label} 정보를 아직 가져오지 못했어요` : r.old ? `${r.label} 정보가 ${ago(r.ok)}째 갱신되지 않았어요` : `${r.label} 정보를 이번에 가져오지 못했어요 (마지막 성공 ${ago(r.ok)} 전)`;
    if (bad.length) banner = one(bad[0]) + (bad.length > 1 ? ` · 그 밖에 ${bad.length - 1}곳` : "") + ".";
  }
  return { rows, banner };
}
