function groupEvents(evs) {
  const m = new Map();
  for (const e of evs) {
    if (!m.has(e.id)) m.set(e.id, { f: BYID[e.id], evs: [], top: "", str: 0 });
    const g = m.get(e.id); g.evs.push(e); if (e.d > g.top) g.top = e.d; g.str = Math.max(g.str, weight(e));
  }
  const arr = [...m.values()];
  for (const g of arr) { g.evs.sort((a, b) => (weight(b) - weight(a)) || (b.d < a.d ? -1 : 1)); g.w = !!WATCH[g.f.id];
    g.bonus = (g.f.cats.includes("ani") || g.f.ex.length) ? 1 : 0; }
  arr.sort((a, b) => (b.w - a.w) || (b.str - a.str) || (b.bonus - a.bonus) || (a.top < b.top ? 1 : a.top > b.top ? -1 : 0) || a.f.t.localeCompare(b.f.t, "ko"));
  return arr;
}
